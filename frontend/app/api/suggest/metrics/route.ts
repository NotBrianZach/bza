import { NextRequest, NextResponse } from 'next/server'
import { getUserFromToken } from '@/lib/apiQuota'
import { describe, measure } from '@/lib/suggest/metrics'
import {
  loadFeedback, loadLatestDigest, loadSettings, previousClusterIds,
} from '@/lib/suggest/store'

/**
 * Is the feed working? The §6 measurements, kept separate.
 *
 * GET /api/suggest/metrics
 *
 * There is no overall score in the response and there must not be one. The
 * spec's closing warning is the reason: "A single 'engagement' number can make
 * a feed more clickable while making it less useful." A caller who wants one
 * number has to choose the weighting themselves, at which point they own it.
 *
 * `prose` is returned alongside the numbers, generated by `describe`, because
 * every rate here is meaningless without its denominator — "100% relevance"
 * over two rated items and over two hundred are different claims, and only one
 * of them is a claim at all. The prose always states the denominator; a caller
 * rendering only the numbers can still get it wrong, but not by accident.
 */

export const dynamic = 'force-dynamic'

export async function GET(req: NextRequest) {
  const userId = await getUserFromToken(req.headers.get('authorization'))
  if (!userId) return NextResponse.json({ error: 'Not signed in' }, { status: 401 })

  try {
    const digest = await loadLatestDigest(userId)
    if (!digest) {
      return NextResponse.json({
        measurements: null,
        reason: 'no digest has been generated yet, so there is nothing to measure',
      })
    }

    const [feedback, previous, settings] = await Promise.all([
      loadFeedback(userId),
      previousClusterIds(userId, digest.digestId),
      loadSettings(userId),
    ])

    const measurements = measure({
      // `StoredDigestItem` extends `ShownItem`, so the rows go straight in —
      // including `backfilled`, which is what keeps the discovery hit rate
      // from being computed over slots that were never discovery.
      shown: digest.items,
      feedback,
      previousClusterIds: previous,
      desiredTopics: settings.desiredTopics,
    })

    return NextResponse.json({
      measurements,
      prose: describe(measurements),
      window: {
        digestId: digest.digestId,
        generatedAt: digest.generatedAt,
        itemsShown: digest.items.length,
        // The gaps and notes from the run itself. A measurement set read
        // without them looks like a verdict on the ranking when the cause was
        // an empty candidate pool.
        gaps: digest.gaps,
        notes: digest.notes,
      },
    })
  } catch (e) {
    return NextResponse.json(
      { error: e instanceof Error ? e.message : 'could not compute the measurements' },
      { status: 500 },
    )
  }
}
