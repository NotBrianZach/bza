import puppeteer from 'puppeteer-core'
const b=await puppeteer.launch({executablePath:process.env.CHROME_PATH,args:['--no-sandbox'],headless:true})
const p=await b.newPage(); await p.setViewport({width:1280,height:1000})
const errs=[]; p.on('response',r=>{if(r.status()>=500)errs.push(`${r.status()} ${r.url().slice(0,90)}`)})
await p.goto('https://aireadalong.com/auth/login',{waitUntil:'networkidle2'})
await p.type('input[type=email]',process.env.BZA_TEST_EMAIL)
await p.type('input[type=password]',process.env.BZA_TEST_PASSWORD)
await p.click('button[type=submit]'); await new Promise(r=>setTimeout(r,6000))
await p.goto('https://aireadalong.com/learn',{waitUntil:'networkidle2'})
await new Promise(r=>setTimeout(r,5000))
// Concepts tab
await p.evaluate(()=>{const b=[...document.querySelectorAll('button')].find(x=>x.textContent.trim()==='Concepts');b&&b.click()})
await new Promise(r=>setTimeout(r,2500))
const heading=await p.evaluate(()=>document.body.innerText.includes('What you have claimed to know'))
console.log('claims section present:',heading)
const before=await p.evaluate(()=>{
  const m=document.body.innerText.match(/What you have claimed to know\s*\n?([^\n]*)/)
  return m?m[1].trim():'(no count line)'})
console.log('count line:',JSON.stringify(before))
const rows=await p.evaluate(()=>[...document.querySelectorAll('button')].filter(b=>/Withdraw/.test(b.textContent)).length)
console.log('withdraw buttons:',rows)
if(rows>0){
  const name=await p.evaluate(()=>{const b=[...document.querySelectorAll('button')].find(x=>/Withdraw/.test(x.textContent));return b.closest('li')?.innerText.split('\n')[0]})
  console.log('withdrawing:',name)
  await p.evaluate(()=>{const b=[...document.querySelectorAll('button')].find(x=>/Withdraw/.test(x.textContent));b.click()})
  await new Promise(r=>setTimeout(r,4000))
  const after=await p.evaluate(()=>[...document.querySelectorAll('button')].filter(b=>/Withdraw/.test(b.textContent)).length)
  const settled=await p.evaluate(n=>{const li=[...document.querySelectorAll('li')].find(x=>x.innerText.startsWith(n));return li?li.innerText.replace(/\n/g,' | '):'(row gone)'},name)
  console.log(`withdraw buttons after: ${after} (was ${rows})`)
  console.log('settled row now reads:',settled)
}
await p.screenshot({path:'/tmp/claims.png',fullPage:false})
console.log('5xx during flow:',errs.length?errs.join(', '):'(none)')
await b.close()
